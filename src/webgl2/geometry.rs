//! Генерация данных для инстансинга.

/// Базовая геометрия: маленький треугольник.
/// Каждый инстанс масштабируется и перемещается через per-instance
/// атрибуты.
pub fn base_triangle() -> [f32; 6] {
    // x, y — две вершины на грань, третья сверху
    return [
        -1.0, -1.0,
         1.0, -1.0,
         0.0,  1.0,
    ];
}

/// Генерирует `n` инстансов с детерминированными параметрами.
///
/// Формат каждого инстанса (6 float):
///   offset.x, offset.y, r, g, b, scale.
///
/// Использует линейный конгруэнтный генератор — воспроизводимый
/// результат без зависимости от `rand`.
pub fn generate_instances(n: usize) -> Vec<f32> {
    let mut state: u32 = 0xC0FFEE;
    let mut next = || -> f32 {
        state = state.wrapping_mul(1_664_525).wrapping_add(1_013_904_223);
        return ((state >> 8) as f32) / 16_777_216.0;
    };
    let mut out = Vec::with_capacity(n * 6);
    for _ in 0..n {
        // Позиция в квадрате [-0.9, 0.9].
        out.push(next() * 1.8 - 0.9);
        out.push(next() * 1.8 - 0.9);
        // Насыщенный цвет: [0.25, 1.0].
        out.push(next() * 0.75 + 0.25);
        out.push(next() * 0.75 + 0.25);
        out.push(next() * 0.75 + 0.25);
        // Масштаб: [0.008, 0.024] — маленькие частицы.
        out.push(next() * 0.016 + 0.008);
    }
    return out;
}